#Menu de operações da calculadora inteligente

print('adição')
print('subtração')
print('multiplicação')
print('divisão')

#Escolha a operação desejada
opção= input('Digite a opção que deseja: ')
print(opção)

#Solicite dois números ao usuário

num1 = float(input('Digite o primeiro número: '))
print(num1)
num2 = float(input('Digite o segundo número: '))
print(num2)

if opção =="adição":
  resultado = num1+num2
  print(f"resultado da soma: {resultado}")
elif opção =="subtração":
  resultado = num1-num2
  print(f"resultado da subtração: {resultado}")
elif opção =="multiplicação":
  resultado = num1*num2
  print(f"resultado da multiplicação: {resultado}")
elif opção =="divisão":
  resultado = num1/num2
  print(f"resultado da divisão: {resultado}")
else:
  print("Opção inválida! Você tinha que escolher de 1 a 4.")